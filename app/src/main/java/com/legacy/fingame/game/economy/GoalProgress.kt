package com.legacy.fingame.game.economy

/**
 * Насколько игрок приблизился к цели — доля цены товара, которая уже лежит на текущем счёте.
 *
 * Считается только текущий счёт: деньги на вкладе заперты до срока, и купить на них товар прямо
 * сейчас нельзя, а полоска цели отвечает именно на вопрос «хватает ли уже».
 *
 * @param balance текущие деньги игрока.
 * @param price цена товара-цели.
 * @return Доля от `0f` до `1f`: `1f`, когда денег хватает, и когда товар ничего не стоит; `0f`,
 * когда денег нет совсем.
 */
fun goalProgress(balance: Int, price: Int): Float = when {
    price <= 0 -> 1f
    balance <= 0 -> 0f
    balance >= price -> 1f
    else -> balance.toFloat() / price
}
